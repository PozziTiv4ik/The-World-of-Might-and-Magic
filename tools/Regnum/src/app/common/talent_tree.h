// Regnum — дерево талантов подкласса героя (как в World of Warcraft): доска из 5 столбцов × ярусы. Слева от ярусов —
// номер яруса и порог очков (0, 10, 20…), у героя — дорожка вложенных очков; финальный ярус (ультимейты) выделен
// золотом и короной. Ячейка — значок (в широкой доске — и название в две строки) и плашка рангов на нижней кромке:
// «1–5» в справочнике, «2/5» у героя; финальный талант (один ранг за 5 очков) — восьмиугольник с золотой каймой и
// плашкой «5 очков». Стрелки от условия к зависимому таланту идут по промежуткам между ячейками. Ширина ячеек
// подстраивается под область: узкая (панель выделения) — только значки, широкая (страница, справочник) — с
// названиями. Одна отрисовка для справочника «Классы героев» (правка: щелчок по пустой ячейке — новый талант,
// перетаскивание — перенос, правый щелчок — меню) и вкладки героя «Таланты» (изученные полностью, частично, доступные
// и закрытые различимы; щелчок — следующий ранг, правый щелчок — снять ранг). Подсказка ячейки — ранги, стоимость,
// условие, модификаторы, описание и причина, почему ранг сейчас не изучить.
#pragma once
#include "app/app.h"

namespace rg::app::talents {

struct Options {
  const HeroClass* cls = nullptr;    // класс (цвет)
  const SubClass* sub = nullptr;     // подкласс: его дерево
  Id hero = 0;                       // 0 — правка дерева (справочник), иначе — изучение героем
  bool interactive = true;           // герой: щелчки изучают и снимают ранги (false — только просмотр)
  Id selected = 0;                   // выбранный талант (правка)
  bool editable = false;             // правка: пустые ячейки и перетаскивание
  std::string mark;                  // метки App::markUi: <mark>, <mark>.cell.<ярус>.<столбец>, <mark>.talent.<ID>, <mark>.tier.<ярус>
};

// Что произошло в этом кадре.
struct Events {
  Id clicked = 0;                    // щелчок по таланту
  Id rightClicked = 0;               // правый щелчок по таланту
  int newRow = -1, newCol = -1;      // правка: щелчок по пустой ячейке
  Id moved = 0;                      // правка: талант перенесён перетаскиванием
  int toRow = -1, toCol = -1;        // в ячейку
};

// Финальный талант (ультимейт): один ранг за наибольшую стоимость (5 очков).
bool isUltimate(const Talent& t);
// Финальный ярус: в нём есть таланты, и все они финальные.
bool ultimateTier(const SubClass& s, int row);
// «1–5», «1–3», «5 очков» — ранги таланта для справочника и подписей.
std::string ranksText(const Talent& t);
// Ярусов показать: занятые + один пустой для новых талантов (при правке), не меньше трёх.
int shownTiers(const SubClass& s, bool editable);
// Высота доски при ширине области width (раскладка ячеек зависит от ширины).
float treeHeight(const SubClass& s, bool editable, float width);
// Наименьшая ширина доски (узкие ячейки только со значками).
float minTreeWidth();
// Дерево в потоке на всю ширину области.
Events tree(App& a, const Options& o);

}  // namespace rg::app::talents
