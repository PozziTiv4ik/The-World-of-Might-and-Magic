// Regnum — базовые записи мира (ТЗ «Добавления в справочники» и «Ввод новых механик», 2026-10-07): должности,
// эссенции элементов, группы ресурсов («Руда», «Звери», «Провизия», «Материалы») с подгруппами и ресурсами,
// религии, встроенные ресурсы (трупы, демоническая энергия, запчасти механизмов), особый отряд «Драконы Бездны» и
// постройка доступа к нему «Цитадель Бездны» (общее дерево).
//
// Новый мир получает их сразу (newWorld); мир прежней версии (Meta::content меньше kVersion) дополняется один раз
// при чтении (нормализация). Записи сопоставляются по названию: существующие не дублируются, а получают группу;
// прежние названия базовых должностей («Канцлер» → «Десница»…) переименовываются вместе с местами совета.
#pragma once
#include "core/world.h"

namespace rg::content {

// Версии: 1 — справочники ТЗ 2026-10-07; 2 — ТЗ «Доработки №1–4» (валюты, морские чудовища, религии, сундуки и
// археологические места, порт, верфь, гильдии, шантирийские постройки, особые отряды, храмы и соборы эссенций,
// ветка технологий «Археология», классы героев, стоимость кораблей, «Гильдия Археологов» у каждого государства).
constexpr int kVersion = 2;

// Дополнить мир базовыми записями версий новее tx.w().meta->content и записать версию. Возвращает, что добавлено
// или изменено (строки для предупреждения нормализации); пусто — мир уже был новой версии.
std::vector<std::string> seed(Tx& tx);

// Название группы ресурсов и её подгрупп из базового набора (для подписей и тестов).
struct BaseGroup {
  const char* key;
  const char* name;
  const char* parent;     // ключ родительской группы; nullptr — верхний уровень
};
const std::vector<BaseGroup>& baseGroups();

// «Гильдия Археологов» — культовая постройка в уникальном дереве государства (ТЗ «Доработки №1», п.10).
Building archGuildFor(Id state, Vec2 pos);

}  // namespace rg::content
