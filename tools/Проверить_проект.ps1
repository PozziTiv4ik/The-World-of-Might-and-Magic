    $characterIndexRows = [regex]::Matches(
        $characterIndex.Text,
        '(?m)^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*`([^`]+\.md)`\s*\|\s*$'
    )

    foreach ($row in $characterIndexRows) {
        $characterRef = $row.Groups[4].Value.Trim()
        if ($characterRef -notlike '03_*') {
            continue
