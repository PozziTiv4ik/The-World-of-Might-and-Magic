    $assetIndexRowsByRef = @{}

    foreach ($line in ($assetIndex.Text -split "\r?\n")) {
        $cells = Convert-WmmaTableRow -Line $line
        if ($null -eq $cells -or $cells.Count -lt 5 -or $cells[0] -eq 'Владелец') {
            continue
        }

        if ($cells[4] -notmatch '`([^`]+\.md)`') {
            continue
        }

        $assetRef = $Matches[1] -replace '\\', '/'
        if ($assetRef -notlike '05_Активы_персонажей/*') {
            continue
        }

        if ($assetIndexRowsByRef.ContainsKey($assetRef)) {
            Add-Problem Error "Duplicate character asset index row: $assetRef"
            continue
        }

        $assetIndexRowsByRef[$assetRef] = [pscustomobject]@{
            Owner = $cells[0]
            Asset = $cells[1]
            Kind = $cells[2]
            Status = $cells[3]
        }

        if (-not (Test-WmmaReference $root $assetRef -FromFile $assetIndex.Path)) {
            Add-Problem Error "Character asset index points to missing file: $assetRef"
        }
    }

    $assetCardRefs = Get-TypePaths 'character_asset'
    foreach ($ref in $assetIndexRowsByRef.Keys) {
        if ($assetCardRefs -notcontains $ref) {
            Add-Problem Error "Character asset index row has no matching character_asset card: $ref"
        }
    }

    foreach ($file in $filesByType['character_asset']) {
        $relativeAsset = Get-WmmaRelativePath $root $file.FullName
        $assetText = Read-WmmaText $file.FullName

        if (-not $assetIndexRowsByRef.ContainsKey($relativeAsset)) {
            Add-Problem Error "Character asset card is missing from asset index: $relativeAsset"
        }

        $owner = Get-WmmaMeta -Text $assetText -Field 'owner'
        $assetKind = Get-WmmaMeta -Text $assetText -Field 'asset_kind'
        $status = Get-WmmaMeta -Text $assetText -Field 'status'
        $visual = Get-WmmaMeta -Text $assetText -Field 'visual'
        $visualStatus = Get-WmmaMeta -Text $assetText -Field 'visual_status'

        foreach ($required in @(
            [pscustomobject]@{ Name = 'owner'; Value = $owner },
            [pscustomobject]@{ Name = 'asset_kind'; Value = $assetKind },
            [pscustomobject]@{ Name = 'status'; Value = $status },
            [pscustomobject]@{ Name = 'visual'; Value = $visual },
            [pscustomobject]@{ Name = 'visual_status'; Value = $visualStatus }
        )) {
            if ([string]::IsNullOrWhiteSpace($required.Value)) {
                Add-Problem Error "Character asset card has empty field '$($required.Name)': $relativeAsset"
            }
        }

        if ($assetKind -and $assetKind -notin @('army', 'unit', 'item', 'fleet', 'organization', 'retinue', 'other')) {
            Add-Problem Error "Character asset card has invalid asset_kind '$assetKind': $relativeAsset"
        }

        if ($visualStatus -and $visualStatus -notin @('missing', 'planned', 'available')) {
            Add-Problem Error "Character asset card has invalid visual_status '$visualStatus': $relativeAsset"
        }

        if ($visualStatus -eq 'available') {
            if ($visual -eq 'null' -or -not (Test-WmmaReference $root $visual -FromFile $file.FullName)) {
                Add-Problem Error "Character asset has visual_status=available but visual file is missing: $relativeAsset"
            }
        } elseif ($visualStatus -eq 'missing' -and $visual -and $visual -ne 'null') {
            Add-Problem Warning "Character asset has visual_status=missing but visual is not null: $relativeAsset"
        }

        if ($assetIndexRowsByRef.ContainsKey($relativeAsset)) {
            $indexRow = $assetIndexRowsByRef[$relativeAsset]
            $assetTitle = Get-WmmaTitle -Text $assetText

            if ($indexRow.Owner -ne $owner) {
                Add-Problem Error "Character asset index owner mismatch: $relativeAsset uses '$($indexRow.Owner)' but card expects '$owner'"
            }

            if ($indexRow.Asset -ne $assetTitle) {
                Add-Problem Error "Character asset index title mismatch: $relativeAsset uses '$($indexRow.Asset)' but card expects '$assetTitle'"
            }

            if ($indexRow.Kind -ne $assetKind) {
                Add-Problem Error "Character asset index type mismatch: $relativeAsset uses '$($indexRow.Kind)' but card expects '$assetKind'"
            }

            if ($indexRow.Status -ne $status) {
                Add-Problem Error "Character asset index status mismatch: $relativeAsset uses '$($indexRow.Status)' but card expects '$status'"
            }
        }
    }
}

