// Regnum — базовые записи мира: должности, эссенции элементов, группы ресурсов («Руда», «Звери», «Провизия»,
// «Материалы») с подгруппами и ресурсами, религии, встроенные ресурсы (трупы, демоническая энергия, запчасти
// механизмов), особые отряды и постройки доступа к ним, сундуки и археологические места, классы героев, ветка
// технологий «Археология» и постройки общего дерева.
//
// Новый мир получает их сразу (newWorld); мир прежней версии (Meta::content меньше kVersion) дополняется один раз
// при чтении (нормализация). Записи сопоставляются по названию: существующие не дублируются, а получают группу;
// прежние названия базовых должностей («Канцлер» → «Десница»…) переименовываются вместе с местами совета.
#pragma once
#include "core/world.h"

namespace rg::content {

// Версии: 1 — должности, группы ресурсов, эссенции, религии, «Драконы Бездны» (core/content_v1.cpp); 2 — валюты,
// морские чудовища, религии, сундуки и археологические места, порт, верфь, гильдии, шантирийские постройки, особые
// отряды, храмы и соборы эссенций, ветка технологий «Археология», классы героев, стоимость кораблей, «Гильдия
// Археологов» у каждого государства (core/content_v2.cpp); 3 — подклассы героев с деревьями талантов, расы, культуры,
// археологические находки и общие артефакты, новые ресурсы и постройки общего дерева, технология «Производство
// магического пороха» (core/content_v3.cpp, core/content_classes.cpp).
constexpr int kVersion = 3;

// Дополнить мир базовыми записями версий новее tx.w().meta->content и записать версию. Возвращает, что добавлено
// или изменено (строки для предупреждения нормализации); пусто — мир уже был новой версии.
std::vector<std::string> seed(Tx& tx);

// Название группы ресурсов и её подгрупп из базового набора (для подписей и тестов).
struct BaseGroup {
  const char* key;
  const char* name;
  const char* parent;     // ключ родительской группы; nullptr — верхний уровень
};
const std::vector<BaseGroup>& baseGroups();

// «Гильдия Археологов» — культовая постройка в уникальном дереве государства.
Building archGuildFor(Id state, Vec2 pos);

}  // namespace rg::content
