// Regnum — правила: предложения и ожидающие решения государств (rules/proposals.cpp). Двустороннее действие игрока
// (сделка с позициями другой стороны, дань, перемирие, союз) ждёт согласия другой стороны или администратора; вопросы
// вассалитета (сюзерен вступает в войну за вассала, вассал отвечает на призыв) ждут решения государства, которого нет
// за этим компьютером. Запись — core/world.h (Proposal); общий заголовок правил — rules/rules.h.
#pragma once
#include "core/world.h"

namespace rg::rules {

// Почему предложение нельзя сделать или принять (пусто — можно): стороны и вид; сделка — validateDeal, перемирие —
// truceProblems, союз — стороны не в войне и не в союзе; вопросы вассалитета — вассалитет и война в силе.
std::vector<std::string> proposalProblems(const World& w, const Proposal& p);
// Записать предложение (ход — текущий); отказ — первая из проблем. Хроника — «A предлагает B: …».
Id propose(Tx& tx, Proposal p);
// Принять: действие выполняется (сделка, дань, перемирие, союз; сюзерен вступает в войну, вассал соглашается), запись
// удаляется. Условия больше не выполнимы — отказ с причиной (запись остаётся).
void acceptProposal(Tx& tx, Id proposal);
// Отклонить: вопросы вассалитета — как отказ (отношения −20 и −10), прочее — запись в хронику; запись удаляется.
void declineProposal(Tx& tx, Id proposal);
// Отозвать (предложившая сторона): запись удаляется без последствий.
void withdrawProposal(Tx& tx, Id proposal);
// Предложения, ждущие ответа государства (to), и предложения государства (from), по ID.
std::vector<Id> proposalsTo(const World& w, Id state);
std::vector<Id> proposalsFrom(const World& w, Id state);
// Предложения, которые стали невозможными (стороны упразднены; перемирие — войны больше нет; союз — стороны в войне
// или уже в союзе; вассалитет снят или война закончилась; сделка между воюющими), удаляются.
void fitProposals(Tx& tx);
// Название предложения для списков: «Перемирие: Арден и Вельмир», «Дань: Вельмир платит Ардену»…
std::string proposalTitle(const World& w, const Proposal& p);

}  // namespace rg::rules
