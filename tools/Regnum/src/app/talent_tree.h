// Regnum — дерево талантов класса героя сеткой (ТЗ «Доработки №4», п.8; как в World of Warcraft): 4 столбца ×
// ярусы, квадратные ячейки со значком и стоимостью, стрелки от условия к зависимому таланту (по промежуткам между
// ячейками), слева — номер яруса и порог очков. Одна отрисовка для справочника «Классы героев» (правка: щелчок по
// пустой ячейке — новый талант, перетаскивание — перенос) и вкладки «Таланты» героя (изученные подсвечены, доступные —
// с золотой рамкой, закрытые приглушены; щелчок — изучить, правый щелчок — отменить).
#pragma once
#include "app/app.h"

namespace rg::app::talents {

struct Options {
  const HeroClass* cls = nullptr;
  Id hero = 0;                       // 0 — правка дерева (справочник), иначе — изучение героем
  Id selected = 0;                   // выбранный талант (правка)
  bool editable = false;             // правка: пустые ячейки и перетаскивание
  std::string mark;                  // префикс меток App::markUi: <mark>.cell.<ряд>.<столбец>, <mark>.talent.<ID>
};

// Что произошло в этом кадре.
struct Events {
  Id clicked = 0;                    // щелчок по таланту
  Id rightClicked = 0;               // правый щелчок по таланту
  int newRow = -1, newCol = -1;      // правка: щелчок по пустой ячейке
  Id moved = 0;                      // правка: талант перенесён перетаскиванием
  int toRow = -1, toCol = -1;        // в ячейку
};

// Высота и ширина сетки для числа ярусов.
float treeHeight(int tiers);
float treeWidth();
// Ярусов показать: занятые + один пустой для новых талантов (при правке), не меньше трёх.
int shownTiers(const HeroClass& c, bool editable);
// Дерево в потоке (по ширине — по середине области).
Events tree(App& a, const Options& o);

}  // namespace rg::app::talents
